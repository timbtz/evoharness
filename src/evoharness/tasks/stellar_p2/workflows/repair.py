"""Persistent database-repair campaign for Stellar P2.

Candidates may reference the provenance-tagged scientific seed directory by
name. The host records seed hashes in campaign state and signed physics
artifacts; candidate source cannot read files or embed coefficient dumps. The
leaderboard bank remains disabled during repair evaluation.

Run with ``python -m evoharness.tasks.stellar_p2.workflows.repair``. Runtime
state defaults to ``.local/runs/stellar-zai-repair-1`` and scientific seeds to
``.local/runs/repair-seeds``.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import time
from pathlib import Path
from typing import Any

from evoharness.paths import RUNS_DIR

from evoharness.engine.campaign_lock import CampaignLock
from evoharness.engine.ledger import BudgetExceeded, BudgetGuard, Ledger
from evoharness.engine.llm import LLM, parse_code, parse_idea, parse_prediction, parse_reasoning
from evoharness.tasks.stellar_p2.discovery.boundaries import enrich_metrics, stable_hash
from evoharness.tasks.stellar_p2.workflows.evaluate import (_evaluator_state, _novelty_record,
                                                _signed, audit_candidate)
from evoharness.tasks.stellar_p2.workflows.discover import (
    CONTINUE_PROMPT, WEB_TOOLS, _metric_summary, _tool_handler, parse_memory,
    response_requests_stop)
from evoharness.tasks.stellar_p2.discovery.census import atomic_json

MODEL = "glm-5.2"
SCHEMA_VERSION = 1
ARM = "database-repair"

STEERING_PATH: Path | None = None  # set by main(); <run_dir>/STEERING.md

SYSTEM = """You are the sole model in a persistent scientific repair loop. You receive a database
of real, provenance-tagged stellarator boundaries (self-generated by this campaign or extracted
from public physics databases — NOT the leaderboard bank) and you write optimizer programs that
REPAIR them toward strict feasibility on the pinned evaluator.

OBJECTIVE, in strict priority order:
1. FEASIBILITY FIRST: minimize the worst normalized constraint violation; the goal is < 0.01.
   The named walls, in order, are EDGE MIRROR RATIO and QI residual. Known levers: m=2 second-order
   (X20-type) cross-section content computed arithmetically on a loaded seed, d(phi)/well-shape
   content, small coherent coefficient steps that trade elongation margin for mirror.
2. Only once a candidate is feasible does score (L_gradB) matter.

Candidate programs load seeds with load_seed(name) / seed_names() (host-injected; the names and
their provenance are listed in the prompt). Embedded numeric coefficient dumps, the public
seed_bank, filesystem, and network access remain forbidden in candidate code — compute
modifications, never paste numbers. Web tools are available to YOU for research; candidates stay
sandboxed and offline.

Every answer must contain, in this order:
Idea: <one sentence describing the repair mechanism>
Prediction: <falsifiable expected change in the worst violation, with numbers>
Memory: <one concise lesson that should persist if this attempt fails or succeeds>
<brief reasoning and source URLs used>
```python
<one complete module defining solve(fm, rng)>
```
Never omit the candidate code and never repeat an identical program. You never decide the campaign
is finished; only the host's hard limits stop it."""


# --------------------------------------------------------------------------
# Seed database
# --------------------------------------------------------------------------

def load_seed_dir(seed_dir: Path) -> list[dict[str, Any]]:
    """Read provenance-tagged seed files: each *.json must hold a boundary
    (or {"boundary": ...}) and should carry meta/provenance. Sorted by name."""
    seeds = []
    for path in sorted(seed_dir.glob("*.json")):
        try:
            payload = json.loads(path.read_text())
        except ValueError:
            continue
        boundary = payload.get("boundary", payload)
        if not (isinstance(boundary, dict) and boundary.get("r_cos")):
            continue
        seeds.append({
            "name": path.stem,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "boundary": boundary,
            "meta": payload.get("meta") or {},
        })
    return seeds


def seed_manifest(seeds: list[dict[str, Any]]) -> list[dict[str, str]]:
    return [{"name": s["name"], "sha256": s["sha256"],
             "provenance": json.dumps(s["meta"], sort_keys=True)[:400]}
            for s in seeds]


def seed_preamble(seeds: list[dict[str, Any]]) -> str:
    """Host-authored module header giving candidates named seed access.
    Generated AFTER the audit passes — the numeric content never appears in
    the model-authored text the audit inspects."""
    packed = {s["name"]: s["boundary"] for s in seeds}
    blob = json.dumps(packed, separators=(",", ":"))
    return (
        "# --- host-injected seed database (provenance-tagged; see run manifest) ---\n"
        "import copy as _evoh_copy, json as _evoh_json\n"
        f"_EVOH_SEEDS = _evoh_json.loads({blob!r})\n"
        "def load_seed(name):\n"
        "    \"\"\"Deep copy of a named seed boundary from the host database.\"\"\"\n"
        "    return _evoh_copy.deepcopy(_EVOH_SEEDS[name])\n"
        "def seed_names():\n"
        "    return sorted(_EVOH_SEEDS)\n"
        "# --- end host-injected seed database ---\n"
    )


def audit_repair_candidate(code: str) -> list[str]:
    """The independent-arm audit, unchanged in its prohibitions (embedded
    numeric blocks, public bank, capabilities) — load_seed()/seed_names()
    references pass because they carry no numeric content."""
    return audit_candidate(code)


# --------------------------------------------------------------------------
# Prompt / memory
# --------------------------------------------------------------------------

def _steering_section() -> str:
    if STEERING_PATH is None or not STEERING_PATH.exists():
        return ""
    text = STEERING_PATH.read_text().strip()
    if not text:
        return ""
    return f"\n## Directive from the host operator\n{text[:6000]}\n"


def _seed_section(seeds: list[dict[str, Any]]) -> str:
    lines = ["## Seed database (load_seed(name) inside candidate code)", ""]
    for s in seeds:
        meta = s["meta"]
        prov = {k: meta[k] for k in ("variant", "nfp", "provenance", "source",
                                     "feasibility", "worst_violation")
                if k in meta}
        lines.append(f"- `{s['name']}`: {json.dumps(prov, sort_keys=True)}")
    return "\n".join(lines)


def _memory_digest(state: dict[str, Any], maximum_chars: int = 18_000) -> str:
    attempts = state.get("attempts", [])
    failures: dict[str, int] = {}
    for row in attempts:
        key = str((row.get("metrics") or {}).get("active_violation") or
                  row.get("status") or "unknown")
        failures[key] = failures.get(key, 0) + 1
    payload = {
        "best_candidate_hash": state.get("best_candidate_hash"),
        "best_selection_score": state.get("best_selection_score"),
        "outcome_counts": failures,
        "recent_attempts": [_metric_summary(row) for row in attempts[-16:]],
    }
    return json.dumps(payload, indent=2, sort_keys=True)[-maximum_chars:]


def build_prompt(task_description: str, state: dict[str, Any],
                 seeds: list[dict[str, Any]], incumbent_code: str | None,
                 round_number: int, runtime_contract: str = "") -> str:
    lineage = ("There is no incumbent yet. Pick the most promising seed(s), diagnose their "
               "violations, and write the first repair optimizer."
               if incumbent_code is None else
               "The incumbent below is this campaign's own best repair so far. Improve it or "
               "attack a different seed/wall; optimize the measured worst violation, not rhetoric.")
    incumbent = incumbent_code or "(none — first repair round)"
    return f"""# Round {round_number} — arm: {ARM} (feasibility-first)

{lineage}

Before proposing code, use web_search at least once. Useful domains: stellarator near-axis theory
(second-order X20 shaping, mirror-ratio control, QI buffer regions), constrained optimization,
homotopy/continuation, and repair/projection methods from other engineering fields. Cite URLs and
translate mechanisms; never paste coefficient dumps into code.

Treat the persistent measurements as ground truth. Do not repeat a failed mechanism with cosmetic
parameter changes. Selection score is the evaluator's shaped score (= -worst violation while
infeasible, = P2 score once feasible), so every reduction of the worst violation is measurable
progress. A candidate that reduces the worst violation of ANY seed below the incumbent's is an
acceptance.
{_steering_section()}
{_seed_section(seeds)}

## Persistent measured memory
{_memory_digest(state)}

## Current incumbent repair program
```python
{incumbent}
```

## Executable task contract
IMPORTANT OVERRIDES: the public seed bank is technically disabled (seed_bank/seed_bank_info are
rejected before evaluation). Candidate code gets host-injected `load_seed(name)` / `seed_names()`
for the database above — reference seeds by name, never inline their numbers.
{runtime_contract}

{task_description}
"""


def memory_markdown(state: dict[str, Any]) -> str:
    attempts = state.get("attempts", [])
    best = next((row for row in attempts
                 if row.get("candidate_hash") == state.get("best_candidate_hash")), None)
    lines = ["# Persistent GLM-5.2 repair memory", "",
             f"Arm: {ARM}. Seeds are provenance-tagged database/self-generated material;",
             "the public leaderboard bank stays disabled. Feasibility first.", ""]
    if best:
        lines.extend(["## Current incumbent", "", json.dumps(
            _metric_summary(best), indent=2, sort_keys=True), ""])
    lines.extend(["## Attempts", ""])
    for row in attempts:
        lines.extend([f"### Round {row.get('round')}", "",
                      json.dumps(_metric_summary(row), indent=2, sort_keys=True), ""])
    return "\n".join(lines).rstrip() + "\n"


