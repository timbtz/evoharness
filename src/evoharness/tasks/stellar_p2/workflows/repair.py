def _initial_state(settings: dict[str, Any], evaluator_fingerprint: str,
                   manifest: list[dict[str, str]]) -> dict[str, Any]:
    return {
        "schema_version": SCHEMA_VERSION,
        "model": MODEL,
        "arm": ARM,
        "bank_disabled": True,
        "created_at": time.time(),
        "settings": settings,
        "evaluator_fingerprint": evaluator_fingerprint,
        "seed_manifest": manifest,
        "round": 0,
        "attempts": [],
        "best_candidate_hash": None,
        "best_candidate_path": None,
        "best_selection_score": None,
    }


def _load_state(run_dir: Path, settings: dict[str, Any],
                evaluator_fingerprint: str,
                manifest: list[dict[str, str]]) -> dict[str, Any]:
    path = run_dir / "state.json"
    if not path.exists():
        return _initial_state(settings, evaluator_fingerprint, manifest)
    state = json.loads(path.read_text())
    if (state.get("schema_version") != SCHEMA_VERSION or state.get("model") != MODEL or
            state.get("arm") != ARM or not state.get("bank_disabled")):
        raise RuntimeError("incompatible campaign state; use a new run directory")
    if state.get("settings") != settings:
        raise RuntimeError("evaluator settings changed; use a new run directory")
    if state.get("evaluator_fingerprint") != evaluator_fingerprint:
        raise RuntimeError("evaluator fingerprint changed; use a new run directory")
    # Seeds may be ADDED between invocations; recorded seeds must not mutate.
    old = {row["name"]: row["sha256"] for row in state.get("seed_manifest", [])}
    new = {row["name"]: row["sha256"] for row in manifest}
    for name, sha in old.items():
        if new.get(name) != sha:
            raise RuntimeError(f"seed {name!r} changed or vanished; "
                               "seed files are append-only for a run directory")
    state["seed_manifest"] = manifest
    return state


def _save_state(run_dir: Path, state: dict[str, Any]) -> None:
    atomic_json(run_dir / "state.json", state)
    (run_dir / "memory.md").write_text(memory_markdown(state))


